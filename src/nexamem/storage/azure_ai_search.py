class AzureAISearchHealthCheck:
    """Health check utilities for Azure AI Search connections."""
    
    @staticmethod
    async def async_health_check(search_client, index_name: str) -> Dict[str, Any]:
        """Perform comprehensive async health check."""
        try:
            start_time = time.time()
            
            # Test connection with a simple search
            results = await search_client.search(search_text="*", top=1)
            
            # Count results (this also tests connectivity)
            count = 0
            async for result in results:
                count += 1
                break
            
            latency = (time.time() - start_time) * 1000  # Convert to ms
            
            return {
                "status": "healthy",
                "latency_ms": round(latency, 2),
                "index_accessible": True,
                "index_name": index_name,
                "can_search": True
            }
        except Exception as e:
            return {
                "status": "unhealthy",
                "error": str(e),
                "error_type": type(e).__name__
            }
    
